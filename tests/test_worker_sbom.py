"""The SBOM worker's Android cataloguers, tested outside the container.

``workers/sbom/analyze.py`` runs inside Docker, but the part most likely to be
wrong is plain parsing: turning the two conventions an APK actually carries into
Maven coordinates. Both are exercised here directly so a bug does not have to
wait for a Docker run to surface.

Why the worker catalogs at all, rather than leaving it to syft: syft has no
Android cataloger. It reports zero artifacts for an APK and zero for a directory
of ``META-INF`` markers, because its Java support reads inside JAR archives and
an APK has none.
"""
from __future__ import annotations

import importlib.util
import sys
import zipfile
from pathlib import Path

import pytest

_WORKER = (Path(__file__).resolve().parent.parent
           / "workers" / "sbom" / "analyze.py")


@pytest.fixture(scope="module")
def worker():
    spec = importlib.util.spec_from_file_location("themob_sbom_worker", _WORKER)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _write(root: Path, relative: str, body: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


# ------------------------------------------------------ the version marker

def test_a_version_marker_becomes_a_maven_coordinate(worker, tmp_path) -> None:
    """``<groupId>_<artifactId>.version`` is the AndroidX convention."""
    _write(tmp_path, "META-INF/androidx.core_core.version", "1.12.0")
    found = worker.catalog_version_markers(str(tmp_path))

    assert len(found) == 1
    entry = found[0]
    assert entry["group"] == "androidx.core"
    assert entry["name"] == "core"
    assert entry["version"] == "1.12.0"
    assert entry["purl"] == "pkg:maven/androidx.core/core@1.12.0"
    assert entry["evidence"] == "META-INF/androidx.core_core.version"


def test_the_split_is_on_the_first_underscore(worker, tmp_path) -> None:
    """Group ids are dotted, artifact ids hyphenated, so the first wins.

    ``androidx.legacy_legacy-support-v4.version`` has to come out as the group
    ``androidx.legacy`` and the artifact ``legacy-support-v4``, not the other
    way round.
    """
    _write(tmp_path, "META-INF/androidx.legacy_legacy-support-v4.version", "1.0.0")
    entry = worker.catalog_version_markers(str(tmp_path))[0]
    assert entry["group"] == "androidx.legacy"
    assert entry["name"] == "legacy-support-v4"


def test_a_marker_outside_meta_inf_is_ignored(worker, tmp_path) -> None:
    """The convention is a META-INF one; elsewhere it is just a file."""
    _write(tmp_path, "assets/androidx.core_core.version", "1.12.0")
    assert worker.catalog_version_markers(str(tmp_path)) == []


@pytest.mark.parametrize("body", ["", "not-a-version", "../../etc/passwd",
                                  "x" * 200])
def test_an_implausible_version_is_refused(worker, tmp_path, body) -> None:
    """A file ending in .version is not automatically a dependency marker."""
    _write(tmp_path, "META-INF/androidx.core_core.version", body)
    assert worker.catalog_version_markers(str(tmp_path)) == []


# ---------------------------------------------------------- pom.properties

def test_pom_properties_becomes_a_maven_coordinate(worker, tmp_path) -> None:
    _write(tmp_path, "META-INF/maven/com.google.code.gson/gson/pom.properties",
           "#Generated by Maven\ngroupId=com.google.code.gson\n"
           "artifactId=gson\nversion=2.8.5\n")
    entry = worker.catalog_pom_properties(str(tmp_path))[0]
    assert entry["purl"] == "pkg:maven/com.google.code.gson/gson@2.8.5"
    assert entry["cataloger"] == "maven-pom-properties"


def test_an_incomplete_pom_is_refused(worker, tmp_path) -> None:
    _write(tmp_path, "META-INF/maven/x/y/pom.properties",
           "groupId=com.example\nartifactId=thing\n")     # no version
    assert worker.catalog_pom_properties(str(tmp_path)) == []


def test_comments_do_not_become_coordinates(worker, tmp_path) -> None:
    _write(tmp_path, "META-INF/maven/x/y/pom.properties",
           "#groupId=evil\ngroupId=com.example\nartifactId=thing\nversion=1.0\n")
    entry = worker.catalog_pom_properties(str(tmp_path))[0]
    assert entry["group"] == "com.example"


# ------------------------------------------------------------------ merging

def test_two_catalogers_agreeing_is_one_library(worker) -> None:
    """Otherwise the same dependency is counted twice in the graph."""
    marker = {"group": "g", "name": "n", "version": "1.0",
              "purl": "pkg:maven/g/n@1.0", "evidence": "a",
              "cataloger": "android-version-marker"}
    pom = dict(marker, evidence="b", cataloger="maven-pom-properties")

    merged = worker.merge([marker], [pom])
    assert len(merged) == 1
    # The agreement is recorded rather than dropped.
    assert "android-version-marker" in merged[0]["cataloger"]
    assert "maven-pom-properties" in merged[0]["cataloger"]


def test_different_versions_are_different_libraries(worker) -> None:
    a = {"group": "g", "name": "n", "version": "1.0",
         "purl": "pkg:maven/g/n@1.0", "evidence": "a", "cataloger": "x"}
    b = dict(a, version="2.0", purl="pkg:maven/g/n@2.0")
    assert len(worker.merge([a], [b])) == 2


def test_the_sbom_grype_reads_is_cyclonedx(worker, tmp_path, monkeypatch) -> None:
    """grype accepts a CycloneDX document, which is what makes this work.

    syft cannot produce one for an Android package, so the worker builds it.
    """
    import json

    sbom = tmp_path / "sbom.json"
    monkeypatch.setattr(worker, "SBOM_PATH", str(sbom))
    worker.write_sbom([{"group": "androidx.core", "name": "core",
                        "version": "1.12.0",
                        "purl": "pkg:maven/androidx.core/core@1.12.0"}])

    document = json.loads(sbom.read_text(encoding="utf-8"))
    assert document["bomFormat"] == "CycloneDX"
    assert document["components"][0]["purl"] == "pkg:maven/androidx.core/core@1.12.0"


# ------------------------------------------------------------- the fixture

def test_the_fixture_apk_is_catalogued(worker, tmp_path) -> None:
    """End to end on the real fixture, without a container.

    The markers exist in the fixture precisely so this stage has something true
    to find, and so a clean library and a vulnerable one can be told apart.
    """
    from tests.fixtures.apk import (CLEAN_LIBRARY, VULNERABLE_LIBRARY,
                                    build_apk)

    apk = build_apk(tmp_path / "shop.apk")
    tree = tmp_path / "tree"
    tree.mkdir()
    with zipfile.ZipFile(apk) as archive:
        archive.extractall(tree)

    merged = worker.merge(worker.catalog_version_markers(str(tree)),
                          worker.catalog_pom_properties(str(tree)))
    purls = {entry["purl"] for entry in merged}
    assert VULNERABLE_LIBRARY in purls
    assert CLEAN_LIBRARY in purls


# --------------------------------------------------------- the whole worker

def test_main_emits_the_contract_the_adapter_reads(worker, tmp_path,
                                                   monkeypatch, capsys) -> None:
    """``main`` end to end, with the two binaries stubbed.

    syft and grype only exist inside the image, so this is the one part of the
    worker that a unit test can otherwise never reach. Everything between the
    catalogers and the JSON on stdout runs for real.
    """
    import json

    _write(tmp_path, "META-INF/androidx.core_core.version", "1.12.0")
    monkeypatch.setattr(worker, "SCAN_DIR", str(tmp_path))
    monkeypatch.setattr(worker, "SBOM_PATH", str(tmp_path / "sbom.json"))
    monkeypatch.setattr(worker, "run_syft", lambda root: [])
    monkeypatch.setattr(worker, "tool_version", lambda binary: "stub")
    monkeypatch.setattr(worker, "run_grype", lambda: ({"matches": [{
        "vulnerability": {"id": "GHSA-test", "severity": "High",
                          "description": "d", "urls": ["u"],
                          "fix": {"versions": ["1.13.0"]},
                          "cvss": [{"metrics": {"baseScore": 7.5}}]},
        "artifact": {"purl": "pkg:maven/androidx.core/core@1.12.0",
                     "name": "core", "version": "1.12.0"},
    }]}, None))

    assert worker.main() == 0
    document = json.loads(capsys.readouterr().out)

    assert document["ok"] is True
    assert document["libraries"][0]["purl"] == "pkg:maven/androidx.core/core@1.12.0"
    vulnerability = document["vulnerabilities"][0]
    assert vulnerability["id"] == "GHSA-test"
    assert vulnerability["fixed_in"] == "1.13.0"
    assert vulnerability["cvss"] == 7.5
    assert document["scanned"]["libraries"] == 1


def test_main_reports_a_grype_failure_rather_than_claiming_success(
        worker, tmp_path, monkeypatch, capsys) -> None:
    """A missing database must not read as "nothing is wrong".

    The container has no network, so if the database were absent grype would
    fail rather than find nothing. Reporting ok here would turn that into a
    clean bill of health for every app.
    """
    import json

    _write(tmp_path, "META-INF/androidx.core_core.version", "1.12.0")
    monkeypatch.setattr(worker, "SCAN_DIR", str(tmp_path))
    monkeypatch.setattr(worker, "SBOM_PATH", str(tmp_path / "sbom.json"))
    monkeypatch.setattr(worker, "run_syft", lambda root: [])
    monkeypatch.setattr(worker, "tool_version", lambda binary: "stub")
    monkeypatch.setattr(worker, "run_grype",
                        lambda: (None, "vulnerability database is empty"))

    assert worker.main() == 0
    document = json.loads(capsys.readouterr().out)
    assert document["ok"] is False
    assert "database" in document["error"]


def test_main_survives_an_unmounted_scan_directory(worker, monkeypatch,
                                                   capsys) -> None:
    import json

    monkeypatch.setattr(worker, "SCAN_DIR", "/definitely/not/here")
    assert worker.main() == 0
    document = json.loads(capsys.readouterr().out)
    assert document["ok"] is False and "not mounted" in document["error"]
